namespace Krypton.Toolkit.Suite.Extended.Card;

/// <summary>
/// Specifies the direction used when expanding or collapsing card body content.
/// </summary>
public enum CardExpandDirection
{
    /// <summary>
    /// Body content slides downward when opening and upward when closing.
    /// </summary>
    SlideDown = 0,

    /// <summary>
    /// Body content slides upward when opening and downward when closing.
    /// </summary>
    SlideUp = 1,
}
